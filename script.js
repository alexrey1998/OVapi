  const paged = { active: false, pages: [], index: 0, pending: false, allowRender: false, timer: null, layoutTimer: null, stop: null, sliding: false };
  function pageCards() {
    return [...departuresContainer.children];
  }
  function resetPageStyles() {
    for (const card of pageCards()) {
      card.classList.remove("page-hidden", "fit-stretched");
      card.style.minHeight = "";
    }
    departuresContainer.style.rowGap = "";
  }
  // Layout of the page starting at card `start`: { count, rowGap, heights }, measured with the cards before it hidden.
  function layoutPageFrom(start) {
    const cards = pageCards();
    resetPageStyles();
    cards.forEach((card, i) => card.classList.toggle("page-hidden", i < start));
    let { rows, screenBottom } = measureRows();
    let firstOut = rows.findIndex(r => r.bottom > screenBottom);
    if (firstOut < 0) return { count: cards.length - start, rowGap: "", heights: [] };
    if (firstOut === 0) return { count: rows[0].cards.length, rowGap: "", heights: [] };
    // Tighter gaps when the row cut by the screen only overflows a little.
    const gap = parseFloat(getComputedStyle(departuresContainer).rowGap) || 0;
    const minGap = Math.round(gap / 3);
    const overflow = rows[firstOut].bottom - screenBottom;
    if (rows[firstOut].top < screenBottom && overflow <= firstOut * (gap - minGap)) {
      departuresContainer.style.rowGap = `${Math.max(minGap, gap - Math.ceil(overflow + 1) / firstOut)}px`;
      ({ rows, screenBottom } = measureRows());
      firstOut = rows.findIndex(r => r.bottom > screenBottom);
      if (firstOut < 0) return { count: cards.length - start, rowGap: departuresContainer.style.rowGap, heights: [] };
    }
    // Stretch the rows of the page to fill the screen (one gap above the bottom).
    const visible = rows.slice(0, firstOut);
    const gapNow = parseFloat(getComputedStyle(departuresContainer).rowGap) || 0;
    const extra = Math.max(0, screenBottom - gapNow - visible[visible.length - 1].bottom) / visible.length;
    const heights = [];
    for (const row of visible) for (const card of row.cards) heights.push(row.bottom - row.top + extra);
    return { count: heights.length, rowGap: departuresContainer.style.rowGap, heights };
  }
  function computePages() {
    const pages = [];
    const total = pageCards().length;
    let start = 0;
    const maxPages = displayMode === "by-time" ? MAX_TIME_PAGES : Infinity;
    while (start < total && pages.length < maxPages) {
      const page = layoutPageFrom(start);
      pages.push({ start, ...page });
      start += Math.max(1, page.count);
    }
    return pages;
  }
  // Shows the cards of several pages one under the other (first one at the top), each with its stretched heights.
  function showPages(list) {
    resetPageStyles();
    const shown = new Map();
    for (const p of list) {
      const page = paged.pages[p];
      if (!page) continue;
      for (let k = 0; k < page.count; k++) shown.set(page.start + k, page.heights[k]);
    }
    pageCards().forEach((card, j) => {
      card.classList.toggle("page-hidden", !shown.has(j));
      const h = shown.get(j);
      if (h !== undefined) {
        card.style.minHeight = `${h}px`;
        card.classList.add("fit-stretched");
      }
    });
    departuresContainer.style.rowGap = paged.pages[list[0]]?.rowGap ?? "";
  }
  function updatePageIndicator(i) {
    if (!pageIndicator) return;
    pageIndicator.classList.toggle("hidden", paged.pages.length <= 1);
    pageIndicator.textContent = `${i + 1}/${paged.pages.length}`;
  }
  function showPage(i) {
    if (!paged.pages[i]) { resetPageStyles(); return; }
    showPages([i]);
    paged.index = i;
    updatePageIndicator(i);
  }
  function paginateAndShow(index = 0) {
    if (!paged.active) return;
    paged.pages = computePages();
    showPage(Math.min(index, Math.max(0, paged.pages.length - 1)));
  }
  function schedulePagination(keepIndex = false) {
    clearTimeout(paged.layoutTimer);
    paged.layoutTimer = setTimeout(() => {
      // Not during a slide: the layout is redone once it has ended.
      if (paged.sliding) schedulePagination(keepIndex);
      else paginateAndShow(keepIndex ? paged.index : 0);
    }, 120);
  }
  // Slide like a scroll: the pages of `list` are shown one under the other, and the whole moves from the top of page
  // `fromPage` to the top of page `toPage` (up for the next page, down for the jump back to the first). Instant when
  // the device asks for reduced motion.
  const SLIDE_MS = 800;
  function slidePages(list, fromPage, toPage, done) {
    const c = departuresContainer;
    if (window.matchMedia("(prefers-reduced-motion: reduce)").matches) { done(); return; }
    showPages(list);
    const topOf = p => pageCards()[paged.pages[p].start].getBoundingClientRect().top;
    const base = topOf(list[0]);
    const from = topOf(fromPage) - base, to = topOf(toPage) - base;
    paged.sliding = true;
    c.style.transition = "none";
    c.style.transform = `translateY(${-from}px)`;
    c.getBoundingClientRect();
    c.style.transition = `transform ${SLIDE_MS}ms ease-in-out`;
    c.style.transform = `translateY(${-to}px)`;
    setTimeout(() => {
      c.style.transition = "none";
      c.style.transform = "";
      paged.sliding = false;
      done();
    }, SLIDE_MS + 30);
  }
  function pageTick() {
    if (!paged.active || paged.sliding) return;
    if (paged.pages.length <= 1) {
      // Safety: a single page recorded while the content overflows the screen (layout measured too early) is redone.
      if (departuresContainer.getBoundingClientRect().bottom > window.innerHeight + 1) paginateAndShow(0);
      return;
    }
    const current = paged.index;
    const next = current + 1;
    if (next < paged.pages.length) {
      updatePageIndicator(next);
      slidePages([current, next], current, next, () => showPage(next));
      return;
    }
    // Back to the first page: everything goes back up, then the data received meanwhile is applied.
    updatePageIndicator(0);
    const all = paged.pages.map((_, i) => i);
    slidePages(all, current, 0, () => {
      if (paged.pending) {
        paged.pending = false;
        paged.allowRender = true;
        renderCurrentMode(lastDepartures);
        paged.allowRender = false;
      }
      paginateAndShow(0);
    });
  }
  function restartPageTimer() {
    clearInterval(paged.timer);
    if (paged.active) paged.timer = setInterval(pageTick, appSettings.pageSeconds * 1000);
  }
  function startPaged() {
    if (isThermoOpen()) closeThermometer();
    expandedLineKey = null;
    paged.active = true;
    paged.pending = false;
    document.body.classList.add("paged");
    window.scrollTo(0, 0);
    paged.allowRender = true;
    renderCurrentMode(lastDepartures);
    paged.allowRender = false;
    enterFullscreen();
    schedulePagination();
    restartPageTimer();
  }
  function stopPaged() {
    if (!paged.active) return;
    paged.active = false;
    clearInterval(paged.timer);
    clearTimeout(paged.layoutTimer);
    document.body.classList.remove("paged");
    paged.sliding = false;
    departuresContainer.style.transition = "";
    departuresContainer.style.transform = "";
    pageIndicator?.classList.add("hidden");
    paged.pages = [];
    resetPageStyles();
    if (paged.pending) {
      paged.pending = false;
      renderCurrentMode(lastDepartures);
    }
    scheduleFullscreenFit();
  }
