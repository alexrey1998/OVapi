// Minute colors (settings): per color { on, a, b }. a is a number ("from a to b min") or a symbol
// (=, <, >, ≤, ≥ applied to b). Enabled rules must not overlap; minutes covered by no rule are muted.
// Paged full screen: seconds per page (settings), at least MIN_PAGE_SECONDS.
const MIN_PAGE_SECONDS = 2;
const MINUTE_COLORS = ["red", "green", "black"];
const DEFAULT_MINUTE_COLORS = {
  red: { on: true, a: "=", b: 0 },
  green: { on: true, a: "1", b: 2 },
  black: { on: true, a: ">", b: 2 }
};
// First field as typed → "=", "<", ">", "≤", "≥" or a whole number as text; null if invalid.
function parseMinuteRuleStart(raw) {
  const v = String(raw ?? "").trim().replace(/\s+/g, "");
  const symbols = { "=": "=", "<": "<", ">": ">", "≤": "≤", "<=": "≤", "=<": "≤", "≥": "≥", ">=": "≥", "=>": "≥" };
  if (v in symbols) return symbols[v];
  return /^\d+$/.test(v) ? String(Number(v)) : null;
}
// Minutes covered by a rule: [min, max] (max may be Infinity), or null when it covers none.
function minuteRuleRange({ a, b }) {
  switch (a) {
    case "=": return [b, b];
    case "<": return b > 0 ? [0, b - 1] : null;
    case "≤": return [0, b];
    case ">": return [b + 1, Infinity];
    case "≥": return [b, Infinity];
    default: return Number(a) <= b ? [Number(a), b] : null;
  }
}
// Problem with a set of rules, as { key, vars } for t(), or null when valid.
function minuteRulesProblem(rules) {
  const enabled = MINUTE_COLORS.filter(c => rules[c]?.on);
  if (!enabled.length) return { key: "mcNoneChecked" };
  const ranges = {};
  for (const c of enabled) {
    const { a, b } = rules[c];
    if (parseMinuteRuleStart(a) === null || !Number.isInteger(b) || b < 0) return { key: "mcInvalid", vars: { color: c } };
    ranges[c] = minuteRuleRange(rules[c]);
    if (!ranges[c]) return { key: /^\d+$/.test(a) ? "mcOrder" : "mcEmpty", vars: { color: c } };
  }
  for (let i = 0; i < enabled.length; i++) {
    for (let j = i + 1; j < enabled.length; j++) {
      const [x, y] = [ranges[enabled[i]], ranges[enabled[j]]];
      if (x[0] <= y[1] && y[0] <= x[1]) return { key: "mcOverlap", vars: { color: enabled[i], color2: enabled[j] } };
    }
  }
  return null;
}
function validMinuteRules(rules) {
  if (!rules || typeof rules !== "object") return false;
  return MINUTE_COLORS.every(c => rules[c] && typeof rules[c].on === "boolean") && minuteRulesProblem(rules) === null;
}
// CSS class for a number of minutes (style.css: .mc-red, .mc-green, .mc-black, .mc-none).
function minuteColorClass(rules, minutes) {
  for (const c of MINUTE_COLORS) {
    if (!rules[c]?.on) continue;
    const r = minuteRuleRange(rules[c]);
    if (r && minutes >= r[0] && minutes <= r[1]) return `mc-${c}`;
  }
  return "mc-none";
}
function minutesUntil(ms, nowMs) {
  return Math.max(0, Math.round((ms - nowMs) / 60000));
}
// Platform change: either a forecast platform differing from the planned one, or a platform marked "12!" by the API.
function platformInfo(dep) {
  const clean = p => (p && p !== "null" ? String(p) : "");
  if (dep.category === "GB") return { platform: "", plannedPlatform: "", platformChanged: false };
  const planned = clean(dep.stop?.platform);
  const forecast = clean(dep.stop?.prognosis?.platform);
  if (forecast && planned && forecast !== planned) return { platform: forecast, plannedPlatform: planned.replace(/!$/, ""), platformChanged: true };
  if (planned.endsWith("!")) return { platform: planned.slice(0, -1), plannedPlatform: "", platformChanged: true };
  return { platform: planned || forecast, plannedPlatform: "", platformChanged: false };
}
// Returns null when the departure is outside the display window.
function toDepartureInfo(dep, nowMs) {
  const schedMs = new Date(dep.stop?.departure).getTime();
  const effMs = Number.isFinite(schedMs) ? withDelay(schedMs, Number(dep.stop?.delay || 0)) : NaN;
  if (!Number.isFinite(effMs) || effMs - nowMs > DISPLAY_WINDOW_MS) return null;
  return {
    dep,
    effMs,
    minutesLeft: minutesUntil(effMs, nowMs),
    timeStr: fmtHM(new Date(schedMs)),
    ...platformInfo(dep),
    trainName: dep.name || "",
    delay: dep.stop?.delay ?? null
  };
}
