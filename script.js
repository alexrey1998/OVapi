// Platform name, with a link to its exact position when quais.csv knows it (clicks on it are skipped by the cards).
function platformLink(dep, platform) {
  const text = escapeHtml(platform);
  const station = dep?.stop?.station;
  const pos = station && platformPositions.get(`${station.id};${platform}`);
  if (!pos) return text;
  return mapLinksHTML(pos, `${station.name || ""} – ${platformWord(dep)} ${platform}`, text);
}
function mapLinkHTML([lat, lon], label, html) {
  const url = mapURL(lat, lon, label);
  const target = url.startsWith("https:") ? ` target="_blank" rel="noopener"` : "";
  return `<a class="platform-link" href="${escapeHtml(url)}"${target}>${html}</a>`;
}
// Text + 📍 link normally; in full screen (style.css: .fs-hide / .fs-only) no 📍, the text itself is the link.
function mapLinksHTML(pos, label, text) {
  return `<span class="fs-hide">${text}${mapLinkHTML(pos, label, "📍")}</span><span class="fs-only">${mapLinkHTML(pos, label, text)}</span>`;
}
// Departures without a platform: same stop, line and destination as departures that have one.
const samePlatformKey = dep => `${dep.stop?.station?.id}|${lineKeyOf(dep)}|${dep.to}`;
// Key above → most frequent platform among the departures that have one.
function knownPlatforms(departures) {
  const counts = new Map();
  for (const dep of departures) {
    const { platform } = platformInfo(dep);
    if (!platform) continue;
    const key = samePlatformKey(dep);
    if (!counts.has(key)) counts.set(key, new Map());
    const c = counts.get(key);
    c.set(platform, (c.get(platform) || 0) + 1);
  }
  const known = new Map();
  for (const [key, c] of counts) known.set(key, [...c].sort((a, b) => b[1] - a[1])[0][0]);
  return known;
}
// "-📍" (only 📍 is a link; in full screen "-" is the link) for a departure without platform: position of the platform known for the same line and destination,
// otherwise of the stop. Empty when neither is known (and for cable cars, which never show a platform).
function approxPlatformHTML(dep, known) {
  const station = dep.stop?.station;
  if (!station || dep.category === "GB") return "";
  const platform = known.get(samePlatformKey(dep));
  const quay = platform && platformPositions.get(`${station.id};${platform}`);
  if (quay) return mapLinksHTML(quay, `${station.name || ""} – ${platformWord(dep)} ${platform}`, "-");
  const { x, y } = station.coordinate || {};
  if (x == null || y == null) return "";
  // transport.opendata.ch: x is the latitude, y the longitude.
  return mapLinksHTML([x, y], station.name || "", "-");
}
