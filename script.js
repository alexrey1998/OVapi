function getLineBadge(category, number, operator) {
  const { categories } = lineColors;
  const withNumber = (prefix) => (number && !number.startsWith("0") ? `${prefix} ${number}` : prefix);
  if (category === "B" || category === "T" || category === "M") {
    return { label: number || category, ...badgeColors(operatorColor(operator, number), categories.default) };
  }
  if (category === "FUN") {
    return { label: withNumber("Funi"), ...badgeColors(operatorColor(operator, number), categories.default) };
  }
  if (category === "BAT") {
    // Boats with their own palette entry (e.g. MGsa M1) show the line only; the others "BAT …" in lineColors.BAT.
    const entry = operatorColor(operator, number);
    if (entry && number) return { label: number, ...badgeColors(entry) };
    return { label: withNumber("BAT"), ...badgeColors(entry, lineColors.BAT || categories.default) };
  }
  if (category === "GB") return { label: "🚠", color: categories.GB };
  const label = withNumber(category);
  if (category === "BN") {
    // Night buses: line number only in the badge; operator palette, exact number only (e.g. VMCV 290),
    // otherwise the same color as the other categories.
    const entry = operator && lineColors[operator]?.[number];
    return { label: number || category, ...badgeColors(entry, lineColors[label] || categories.trainsColor) };
  }
  if (categories.trains.includes(category)) return { label, ...badgeColors(categories.trainColors?.[category], categories.trainsColor) };
  // lineColors[label]: extension point for colors by label.
  return { label, color: lineColors[label] || categories.trainsColor };
}
// Operator palette lookup: exact number, then its numeric part, then "default".
function operatorColor(operator, number) {
  const palette = operator && lineColors[operator];
  if (!palette) return "";
  return palette[number] || palette[number.match(/^\d+/)?.[0]] || palette.default;
}
// Line key "category number". Outside bus/tram/metro, a number starting with 0 is a train number
// (TGV, EC, TER… without a line number): such departures are grouped by category, like their badge.
function lineKeyOf(dep) {
  const category = dep.category || "";
  const number = dep.number || "";
  const isTrainNumber = !["B", "T", "M"].includes(category) && number.startsWith("0");
  return `${category} ${isTrainNumber ? "" : number}`;
}
// Numeric line numbers first (by value), then alphabetical.
function compareLineKeys(a, b) {
  const numA = a.split(" ").pop();
  const numB = b.split(" ").pop();
  const pureNumA = parseInt(numA.match(/^\d+/)?.[0]);
  const pureNumB = parseInt(numB.match(/^\d+/)?.[0]);
  const isNumA = !isNaN(pureNumA);
  const isNumB = !isNaN(pureNumB);
  if (isNumA && isNumB) return pureNumA !== pureNumB ? pureNumA - pureNumB : numA.localeCompare(numB);
  if (isNumA) return -1;
  if (isNumB) return 1;
  return numA.localeCompare(numB) || a.localeCompare(b);
}
