  // Rows of cards (same top), with the row cut by the bottom of the screen if any.
  function measureRows() {
    const rows = [];
    for (const card of departuresContainer.children) {
      if (card.classList.contains("page-hidden")) continue;
      const r = card.getBoundingClientRect();
      const row = rows.find(x => Math.abs(x.top - r.top) < 2);
      if (row) { row.cards.push(card); row.bottom = Math.max(row.bottom, r.bottom); }
      else rows.push({ top: r.top, bottom: r.bottom, cards: [card] });
    }
    const screenBottom = window.innerHeight;
    const cutIndex = rows.findIndex(r => r.top < screenBottom && r.bottom > screenBottom);
    return { rows, screenBottom, cutIndex };
  }
  function fitFullscreenRows() {
    if (document.body.classList.contains("paged")) return;
    clearFullscreenFit();
    if (!document.body.classList.contains("fullscreen") || departuresContainer.style.display === "none") return;
    if (scrolledTop() > 0) return;
    let { rows, screenBottom, cutIndex } = measureRows();
    if (cutIndex < 0) return;

    // 1. Tighter gaps when the overflow is small enough.
    const gap = parseFloat(getComputedStyle(departuresContainer).rowGap) || 0;
    const minGap = Math.round(gap / 3);
    const overflow = rows[cutIndex].bottom - screenBottom;
    if (cutIndex > 0 && overflow <= cutIndex * (gap - minGap)) {
      departuresContainer.style.rowGap = `${Math.max(minGap, gap - Math.ceil(overflow + 1) / cutIndex)}px`;
      fitApplied = true;
      ({ rows, screenBottom, cutIndex } = measureRows());
      if (cutIndex < 0) return;
    }

    // 2. Stretch the visible rows to push the cut row just below the screen.
    const visible = rows.slice(0, cutIndex);
    if (!visible.length) return;
    const extra = (screenBottom + 1 - rows[cutIndex].top) / visible.length;
    for (const row of visible) {
      for (const card of row.cards) {
        card.style.minHeight = `${row.bottom - row.top + extra}px`;
        card.classList.add("fit-stretched");
      }
    }
    fitApplied = true;
  }
