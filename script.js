// Default map app: Apple Plans on iOS, the geo: app on Android (Google Maps if none), Google Maps elsewhere.
function mapURL(lat, lon, label) {
  const google = `https://www.google.com/maps/search/?api=1&query=${lat},${lon}`;
  const ua = navigator.userAgent;
  if (/iPhone|iPad|iPod/.test(ua) || (/Macintosh/.test(ua) && navigator.maxTouchPoints > 1)) {
    return `https://maps.apple.com/?ll=${lat},${lon}&q=${encodeURIComponent(label)}`;
  }
  if (/Android/.test(ua)) {
    return `intent:${lat},${lon}?q=${lat},${lon}(${encodeURIComponent(label)})#Intent;scheme=geo;S.browser_fallback_url=${encodeURIComponent(google)};end`;
  }
  return google;
}
